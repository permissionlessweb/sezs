#!/usr/bin/env bash
# Derive Mermaid diagrams from the SEZS stack with Trailmark 0.8+
# (`trailmark diagram`), following Trail of Bits' diagramming-code skill:
# https://github.com/trailofbits/skills/blob/main/plugins/trailmark/skills/diagramming-code/SKILL.md
# Loopback/local only. Does not start services or touch the walkthrough session.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/docs/flows/derived"
SUMMARY="${OUT}/ANALYZE-SUMMARY.md"
export PATH="${HOME}/.local/bin:/opt/homebrew/bin:${PATH}"

mkdir -p "${OUT}"

if ! command -v trailmark >/dev/null 2>&1; then
  echo "trailmark is not on PATH. Install with: uv tool install trailmark" >&2
  exit 1
fi

echo "# Trailmark derived graphs" > "${SUMMARY}"
echo >> "${SUMMARY}"
echo "Generated by \`scripts/flows-derive.sh\` with $(trailmark --version 2>/dev/null || trailmark version)." >> "${SUMMARY}"
echo >> "${SUMMARY}"
echo "Diagram CLI: native \`trailmark diagram\` (version gate passed; Trailmark 0.8.0)." >> "${SUMMARY}"
echo "Skill: [plugins/trailmark/skills/diagramming-code/SKILL.md](https://github.com/trailofbits/skills/blob/main/plugins/trailmark/skills/diagramming-code/SKILL.md) in [trailofbits/skills](https://github.com/trailofbits/skills)." >> "${SUMMARY}"
echo >> "${SUMMARY}"

analyze() {
  local name="$1" lang="$2" target="$3"
  echo "## ${name}" >> "${SUMMARY}"
  echo >> "${SUMMARY}"
  echo "- path: \`${target}\`" >> "${SUMMARY}"
  echo "- language: \`${lang}\`" >> "${SUMMARY}"
  echo >> "${SUMMARY}"
  if [[ ! -d "${ROOT}/${target}" ]]; then
    echo "SKIP analyze ${name}: missing ${target}" | tee -a "${SUMMARY}"
    echo >> "${SUMMARY}"
    return 0
  fi
  echo "analyze ${name} (${lang}) <- ${target}"
  if trailmark analyze --language "${lang}" --summary "${ROOT}/${target}" >> "${SUMMARY}" 2>"${OUT}/${name}.analyze.err"; then
    rm -f "${OUT}/${name}.analyze.err"
  else
    echo "ANALYZE FAILED ${name}" | tee -a "${SUMMARY}"
    sed 's/^/    /' "${OUT}/${name}.analyze.err" >> "${SUMMARY}" || true
  fi
  echo >> "${SUMMARY}"
}

derive() {
  local name="$1" lang="$2" target="$3" typ="$4"
  shift 4
  local mmd="${OUT}/${name}.mmd"
  if [[ ! -d "${ROOT}/${target}" ]]; then
    echo "SKIP diagram ${name}: missing ${target}"
    return 0
  fi
  echo "diagram ${name} (${typ}) <- ${target} $*"
  local err="${mmd}.err"
  if trailmark diagram --target "${ROOT}/${target}" --language "${lang}" --type "${typ}" "$@" > "${mmd}.tmp" 2>"${err}"; then
    if grep -qE '^(flowchart|classDiagram)' "${mmd}.tmp"; then
      mv "${mmd}.tmp" "${mmd}"
      rm -f "${err}"
      echo "  wrote ${mmd}"
    else
      echo "EMPTY or malformed ${name}" >&2
      cat "${mmd}.tmp" >> "${err}" || true
      rm -f "${mmd}.tmp"
    fi
  else
    echo "DIAGRAM FAILED ${name}" >&2
    cat "${err}" >&2 || true
    rm -f "${mmd}.tmp"
  fi
}

# --- analyze (summaries for the baseline) ---
analyze sezs-orch rust packages/sezs-orch
analyze sezs-circuit-orch rust packages/sezs-circuit-orch
analyze cw-event-manifold rust contracts/cw-ave/contracts/cw-event-manifold
analyze cw420 rust contracts/cw-ave/contracts/cw420
analyze sezs-ticket-v2 rust circuits/sezs-ticket-v2/circuit
analyze app-event typescript apps/sezs/src/event
analyze app-pay typescript apps/sezs/src/pay
analyze app-frost typescript apps/sezs/src/frost
analyze app-auth typescript apps/sezs/src/auth
analyze app-zafu javascript apps/sezs/src/zafu

# --- diagrams (ToB types) ---
derive sezs-orch-module-deps rust packages/sezs-orch module-deps --direction LR
derive sezs-orch-deploy rust packages/sezs-orch call-graph --focus deploy_on --depth 2
derive sezs-orch-circuit-upload rust packages/sezs-orch call-graph --focus compile_and_upload_circuit --depth 2
derive sezs-orch-curate rust packages/sezs-orch call-graph --focus curate_msgs --depth 2

derive sezs-circuit-orch-module-deps rust packages/sezs-circuit-orch module-deps --direction LR

derive manifold-module-deps rust contracts/cw-ave/contracts/cw-event-manifold module-deps --direction LR
derive manifold-execute rust contracts/cw-ave/contracts/cw-event-manifold call-graph --focus execute --depth 2
derive manifold-verify rust contracts/cw-ave/contracts/cw-event-manifold call-graph --focus verify_ticket_proof --depth 2

derive cw420-module-deps rust contracts/cw-ave/contracts/cw420 module-deps --direction LR

derive circuit-module-deps rust circuits/sezs-ticket-v2/circuit module-deps --direction LR
derive circuit-prove rust circuits/sezs-ticket-v2/circuit call-graph --focus prove --depth 2
derive circuit-commitment rust circuits/sezs-ticket-v2/circuit call-graph --focus commitment --depth 2

derive app-event-module-deps typescript apps/sezs/src/event module-deps --direction LR
derive app-usher-door typescript apps/sezs/src/event call-graph --focus UsherDoor --depth 2
derive app-checkout typescript apps/sezs/src/event call-graph --focus CheckoutPanel --depth 2
derive app-ticket-vault typescript apps/sezs/src/event call-graph --focus TicketVault --depth 2
derive app-prepare-consume typescript apps/sezs/src/event call-graph --focus prepareConsumeV3 --depth 2
derive app-submit-consume typescript apps/sezs/src/event call-graph --focus submitConsumeV3 --depth 2

derive app-pay-module-deps typescript apps/sezs/src/pay module-deps --direction LR
derive app-frost-module-deps typescript apps/sezs/src/frost module-deps --direction LR
derive app-auth-module-deps typescript apps/sezs/src/auth module-deps --direction LR
derive app-zafu-open-room javascript apps/sezs/src/zafu call-graph --focus openLabRoom --depth 2

echo "Derived diagrams in ${OUT}"
ls -1 "${OUT}"/*.mmd 2>/dev/null | wc -l
